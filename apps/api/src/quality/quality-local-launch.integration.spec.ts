import { execFileSync } from 'node:child_process';
import { randomUUID } from 'node:crypto';
import { mkdtempSync, rmSync } from 'node:fs';
import { createRequire } from 'node:module';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { PrismaClient } from '@prisma/client';
import { afterAll, beforeAll, expect, it, vi } from 'vitest';
import { LocalTestRunsService } from './local-test-runs.service';
import { QualityLocalLaunchService } from './quality-local-launch.service';
import { LocalLaunchTicketStore } from '../workflow/local-launch-ticket.store';
const directory = mkdtempSync(join(tmpdir(), 'flowx-quality-launch-'));
const url = `file:${join(directory, 'test.db')}`;
const prisma = new PrismaClient({ datasources: { db: { url } } });
beforeAll(() => {
  const cli = createRequire(resolve('package.json')).resolve('prisma/build/index.js');
  const env = { ...process.env, DATABASE_URL: url };
  const sql = execFileSync(process.execPath, [cli, 'migrate', 'diff', '--from-empty', '--to-schema-datamodel', resolve('../../prisma/schema.prisma'), '--script'], { env, encoding: 'utf8' });
  execFileSync(process.execPath, [cli, 'db', 'execute', '--url', url, '--stdin'], { env, input: sql, stdio: ['pipe', 'pipe', 'pipe'] });
}, 30_000);
afterAll(async () => { await prisma.$disconnect(); rmSync(directory, { recursive: true, force: true }); });
it('真实 SQLite 票据兑换绑定原用户组织和设备，交接失败释放租约且不伪造测试结果', async () => {
  const organization = await prisma.organization.create({ data: { provider: 'test', providerOrganizationId: randomUUID(), name: '质量组织' } });
  const user = await prisma.user.create({ data: { displayName: '测试人' } });
  await prisma.userOrganization.create({ data: { userId: user.id, organizationId: organization.id } });
  const workspace = await prisma.workspace.create({ data: { name: '工作区', organizationId: organization.id } });
  const project = await prisma.project.create({ data: { name: '项目', workspaceId: workspace.id } });
  const version = await prisma.projectVersion.create({ data: { name: 'v1', projectId: project.id } });
  const requirement = await prisma.requirement.create({ data: { title: '需求', description: '测试', acceptanceCriteria: '完成', projectId: project.id } });
  const workflow = await prisma.workflowRun.create({ data: { requirementId: requirement.id, status: 'DONE' } });
  const repository = await prisma.workflowRepository.create({ data: { workflowRunId: workflow.id, name: '仓库', url: 'https://github.com/org/repo.git', baseBranch: 'main', workingBranch: 'feature' } });
  const request = await prisma.testRequest.create({ data: { title: '提测', workspaceId: workspace.id, projectId: project.id, projectVersionId: version.id, traceId: randomUUID(), status: 'IN_TEST', scopeGenerationStatus: 'COMPLETED', workflowLinks: { create: { workflowRunId: workflow.id } } } });
  const plan = await prisma.testPlan.create({ data: { testRequestId: request.id } });
  const snapshot = await prisma.testCaseSnapshot.create({ data: { testPlanId: plan.id, title: '功能用例', priority: 'P1', kind: 'FUNCTIONAL', steps: ['执行'], expected: '成功' } });
  const run = await prisma.testRun.create({ data: { testPlanId: plan.id, name: '初测', runType: 'INITIAL', executionMode: 'LOCAL', status: 'ACTIVE', sourceFingerprint: randomUUID() } });
  const target = await prisma.testRunTarget.create({ data: { testRunId: run.id, key: 'web', name: 'Web', expectedRevisions: [{ workflowRepositoryId: repository.id, branch: 'feature', headSha: 'abc' }] } });
  await prisma.testRunCase.create({ data: { testRunId: run.id, targetId: target.id, snapshotId: snapshot.id } });
  const runs = new LocalTestRunsService(prisma as never, {} as never);
  const auth = { createShortLivedSession: vi.fn(async () => ({ token: 'short-token', expiresAt: new Date(Date.now() + 10000) })) };
  const launch = new QualityLocalLaunchService(prisma as never, runs, auth as never, new LocalLaunchTicketStore());
  const session = { user: { id: user.id }, organization: { id: organization.id } };
  const ticket = await launch.issueTicket(run.id, { targetId: target.id }, session);
  expect(await prisma.testExecution.count()).toBe(0);
  const redeemed = await launch.redeemTicket(ticket.ticket, 'device-1');
  expect(await prisma.executionSession.findUnique({ where: { id: redeemed.executionSessionId } })).toMatchObject({ testRunId: run.id, claimedByUserId: user.id, organizationId: organization.id, projectId: project.id, deviceId: 'device-1', status: 'RUNNING' });
  expect(await prisma.testRunCaseLease.count()).toBe(1);
  await expect(launch.redeemTicket(ticket.ticket, 'device-2')).rejects.toThrow();
  await runs.control(redeemed.executionSessionId, 'release', { reason: '模拟IDE失败' }, { userId: user.id, organizationId: organization.id });
  const retry = await launch.issueTicket(run.id, { targetId: target.id }, session);
  auth.createShortLivedSession.mockRejectedValueOnce(new Error('auth unavailable'));
  await expect(launch.redeemTicket(retry.ticket, 'device-1')).rejects.toThrow('auth unavailable');
  expect(await prisma.testRunCaseLease.count()).toBe(0);
  expect(await prisma.executionSession.count({ where: { status: 'RUNNING' } })).toBe(0);
  expect(await prisma.testResult.count()).toBe(0);
});
